    /* จำลองการเล่นด้วยกติกาจริง (ผลคงที่ทุกครั้งเพราะกำหนด seed) */
    function simulate(board, set, teamNames, meta, pRight, seed) {
        const g = Engine.newGame(board, set, teamNames.map((name) => ({ name })), { time: 30, rightStep: 2, wrongStep: 2 }, Object.assign({ seed }, meta));
        const rand = Engine.rng(seed * 7 + 1);
        let guard = 0;
        while (!Engine.isOver(g) && guard < 2000) {
            guard += 1;
            if (g.phase === 'question') {
                const q = Engine.pendingQuestion(g);
                const ok = rand() < pRight;
                let given = null;
                if (q.type === 'mc') given = ok ? q.answer : (q.answer + 1) % 4;
                else if (q.type === 'tf') given = ok ? String(q.answer) : String(!q.answer);
                else given = ok ? Engine.answersOf(q)[0] : 'ไม่ทราบ';
                Engine.answer(g, ok, given, 5 + Math.floor(rand() * 20));
            } else Engine.roll(g, 1 + Math.floor(rand() * 6));
        }
        return g;
    }

