    /* สุ่มแบบกำหนดค่าเริ่มต้นได้ (ผลตัวอย่างเหมือนเดิมทุกครั้ง) */
    function rng(seed) {
        let x = seed >>> 0;
        return () => { x = (x * 1664525 + 1013904223) >>> 0; return x / 4294967296; };
    }

    /* จำลองการแข่งขันด้วยเครื่องยนต์จริง → บันทึกผลที่สมจริง */
    function simulate(o) {
        const rand = rng(o.seed);
        let t = o.start;
        const step = (s, a) => { t += a.wait || 4000; return Engine.reduce(s, Object.assign({ at: t }, a)).state; };
        let s = Engine.newLive({ id: o.id, title: o.title, subtitle: o.subtitle, setName: o.set.name, dateText: o.dateText, mode: o.mode, opts: o.opts, teams: o.teams, deck: o.deck }, t);
        const skill = o.teams.map((tm, i) => o.skill[i]);
        // สลับลำดับแบบ Fisher-Yates (sort กับตัวเปรียบเทียบสุ่มให้ผลต่างกันในแต่ละเบราว์เซอร์)
        const shuffled = (n) => { const a = [...Array(n).keys()]; for (let i = n - 1; i > 0; i -= 1) { const j = Math.floor(rand() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
        if (o.mode === 'jeopardy') {
            const order = o.deck.slice(0, o.play || o.deck.length);
            order.forEach((q, n) => {
                s = step(s, { type: 'pick', qid: q.id, team: s.turn });
                const tries = shuffled(s.teams.length);
                let done = false;
                for (const i of tries) {
                    if (done || rand() < 0.15) continue;
                    s = step(s, { type: 'buzz', team: s.teams[i].id, wait: 2500 + Math.floor(rand() * 4000) });
                    const ok = rand() < skill[i] - (Number(q.points) || 100) / 2500;
                    s = step(s, { type: 'judge', result: ok, wait: 5000 });
                    if (ok) done = true;
                    if (n % 7 === 6) break;
                }
                if (!done) s = step(s, { type: 'reveal' });
                s = step(s, { type: 'next' });
            });
        } else {
            o.deck.forEach(() => {
                s = step(s, { type: 'show', wait: 3000 });
                if (o.mode === 'buzz') {
                    const tries = shuffled(s.teams.length);
                    let done = false;
                    for (const i of tries.slice(0, 3)) {
                        if (done) break;
                        s = step(s, { type: 'buzz', team: s.teams[i].id, wait: 2000 + Math.floor(rand() * 5000) });
                        const ok = rand() < skill[i];
                        s = step(s, { type: 'judge', result: ok, wait: 4000 });
                        done = ok;
                    }
                    if (!done) s = step(s, { type: 'reveal' });
                } else {
                    const q = Engine.current(s);
                    s.teams.forEach((tm, i) => {
                        const ok = rand() < skill[i];
                        if (Engine.isChoice(q) && o.mode === 'mc') {
                            const wrong = [0, 1, 2, 3].filter((c) => c !== q.answer && c < q.choices.length);
                            s = step(s, { type: 'choose', team: tm.id, choice: ok ? q.answer : wrong[Math.floor(rand() * wrong.length)], wait: 1500 });
                        } else s = step(s, { type: 'mark', team: tm.id, result: ok, wait: 1500 });
                    });
                    s = step(s, { type: 'reveal' });
                }
                s = step(s, { type: 'next', wait: 6000 });
            });
        }
        (o.adjusts || []).forEach((a) => { s = step(s, { type: 'adjust', team: s.teams[a.i].id, delta: a.delta, note: a.note }); });
        s = step(s, { type: 'finish' });
        return Engine.toRecord(s, { place: o.place, judges: o.judges, note: o.note || '' });
    }

